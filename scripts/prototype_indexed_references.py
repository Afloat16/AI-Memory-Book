PLAN = ROOT / "benchmarks/experiments/indexed-references-prototype-plan.json"
REFERENCE_KEYS = frozenset(("project", "session_id", "turn_index"))
ENCODINGS = ("cl100k_base", "o200k_base")
BUDGETS = (2000, 4000, 8000)
ADDED_TOOL_DESCRIPTION = (
    "\nsource_format='indexed' opts into indexed-v1: source_sessions contains "
    "[project,session_id] pairs; source_refs entries become [session_index,turn_index] "
    "or [session_index,turn_index,extra_fields]. Expand the table to recover references. "
    "Context and provenance are unchanged. Default objects preserves the existing format."
)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def encode(payload):
    if "source_sessions" in payload or "source_format" in payload:
        raise ValueError("Input already has a source encoding")
    sessions, positions, results = [], {}, []
    for item in payload["results"]:
        refs = []
        for ref in item["source_refs"]:
            key = (ref["project"], ref["session_id"])
            if key not in positions:
                positions[key] = len(sessions)
                sessions.append(list(key))
            encoded = [positions[key], ref["turn_index"]]
            extra = {k: v for k, v in ref.items() if k not in REFERENCE_KEYS}
            if extra:
                encoded.append(extra)
            refs.append(encoded)
        results.append({**item, "source_refs": refs})
    return {**payload, "results": results, "source_sessions": sessions, "source_format": "indexed-v1"}


def decode(payload):
    if payload["source_format"] != "indexed-v1":
        raise ValueError("Unknown indexed reference version")
    sessions, results = payload["source_sessions"], []
    for item in payload["results"]:
        refs = []
        for entry in item["source_refs"]:
            if len(entry) not in (2, 3) or type(entry[0]) is not int or not 0 <= entry[0] < len(sessions):
                raise ValueError("Invalid indexed reference")
            project, session = sessions[entry[0]]
            extra = entry[2] if len(entry) == 3 else {}
            if REFERENCE_KEYS.intersection(extra):
                raise ValueError("Extra fields cannot replace reference identity")
            refs.append({"project": project, "session_id": session, "turn_index": entry[1], **extra})
        results.append({**item, "source_refs": refs})
    return {**{k: v for k, v in payload.items() if k not in ("source_sessions", "source_format")}, "results": results}


def stats(values):
    return {"n": len(values), "mean": statistics.fmean(values), "p50": percentile(values, .5),
            "p95": percentile(values, .95), "min": min(values), "max": max(values)}


async def proposed_metadata(database):
    from mcp.server.fastmcp import FastMCP
    from mcp.types import ListToolsResult
    from pydantic import StrictBool, StrictInt

    # Actual shipped schemas for all six tools; no production module is edited.
    original = await create_server(database).list_tools()
    recall = next(tool for tool in original if tool.name == "recall_memory")
    proposed = FastMCP("IndexedReferencePrototype")

    def signature(query: str, project: str | None = None, chapter: str | None = None,
                  session: str | None = None, budget_chars: int = 4000, limit: int = 5,
                  details: bool = False, coverage: bool = False,
                  budget_tokens: StrictInt | None = None, tokenizer: str = "cl100k_base",
                  semantic: StrictBool = False, source_format: Literal["objects", "indexed"] = "objects") -> str:
        raise RuntimeError("Schema-only prototype; do not execute")

    # Local StrictInt/StrictBool are not available to get_type_hints when the
    # module uses postponed annotations. Resolve the supplied signature types.
    signature.__annotations__.update(budget_tokens=StrictInt | None, semantic=StrictBool)
    signature.__name__ = "recall_memory"
    proposed.add_tool(signature, name="recall_memory", description=recall.description + ADDED_TOOL_DESCRIPTION,
                      annotations=recall.annotations, structured_output=False)
    replacement = (await proposed.list_tools())[0]
    expected_schema = copy.deepcopy(recall.inputSchema)
    field = replacement.inputSchema["properties"]["source_format"]
    expected_schema["properties"]["source_format"] = field
    if expected_schema != replacement.inputSchema:
        raise ValueError("Prototype unexpectedly changed existing schema fields")
    updated = [replacement if tool.name == "recall_memory" else tool for tool in original]
    instructions = INSTRUCTIONS + "This connection is read-only; remember_session is not available.\n"
    return {"baseline_schema": ListToolsResult(tools=original).model_dump_json(exclude_none=True),
            "proposed_schema": ListToolsResult(tools=updated).model_dump_json(exclude_none=True),
            "baseline_instructions": instructions, "proposed_instructions": instructions,
            "added_tool_description": ADDED_TOOL_DESCRIPTION, "source_format_property": field,
            "scope": "Exact SDK-generated projection of the proposed signature and tool description. Global instructions remain unchanged; no live API is modified."}


def summarize(rows):
    costs = {}
    for encoding in ENCODINGS:
        selected = [row["costs"][encoding] for row in rows]
        fields = selected[0].keys()
        costs[encoding] = {key: stats([r[key] for r in selected]) for key in fields}
        for surface in ("text", "envelope"):
            savings = [r["first_call_net_" + surface] for r in selected]
            costs[encoding]["first_call_" + surface + "_outcomes"] = {
                "saves_tokens": sum(v > 0 for v in savings), "equal_tokens": sum(v == 0 for v in savings),
                "adds_tokens": sum(v < 0 for v in savings)}
    return {"queries": len(rows), "source_refs": sum(r["source_refs"] for r in rows),
            "empty_responses": sum(r["results"] == 0 for r in rows),
            "all_reversible": all(r["reversible"] for r in rows), "costs": costs}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--locomo-path", type=Path, required=True)
    parser.add_argument("--reference-report", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error("Select a new output path")
    import tiktoken
    from mcp.types import CallToolResult, TextContent
    if tiktoken.__version__ != "0.12.0" or importlib.metadata.version("mcp") != "1.30.0":
        raise ValueError("Use the pinned tokenizer and SDK versions")
    encodings = {name: tiktoken.get_encoding(name) for name in ENCODINGS}
    def count(name, text):
        return len(encodings[name].encode(text, disallowed_special=()))
    def envelope(text):
        return CallToolResult(content=[TextContent(type="text", text=text)], isError=False).model_dump_json(exclude_none=True)
    reference_raw = gzip.decompress(args.reference_report.read_bytes())
    reference = json.loads(reference_raw)
    if not reference["validation"]["passed"] or sha(reference_raw) != "ded0d6908fd1f5926b3ac379e496c9e05df7fea63cb0ed5e1d3f1b8b93a6d77d":
        raise ValueError("Reference must be the already audited default-performance measurement")
    expected = {(w["cohort"], c["budget_chars"], row["query_id"]): row
                for w in reference["workers"] if w["label"] == "candidate" and w["round"] == 0
                for c in w["configurations"] if c["surface"] == "mcp_stdio" for row in c["rows"]}
    provenance = checkout_provenance(ROOT / "src/memory_book")
    source_hash = engine_source_hash(ROOT / "src/memory_book")
    if not provenance["commit_identifies_source"] or source_hash != "a7c3a3e39677770809022a3289d8337c54b3bfec992cf1fef4779fd081fc8bdb":
        raise ValueError("Runtime differs from the frozen performance candidate")
    plan = json.loads(PLAN.read_text())
    report = {"schema_version": 1, "created_at": datetime.now(timezone.utc).isoformat(),
              "plan": plan, "plan_sha256": sha(PLAN.read_bytes()), "source_sha256": source_hash,
              "source_provenance": provenance, "prototype_sha256": sha(Path(__file__).read_bytes()),
              "reference_report_sha256": sha(reference_raw), "configurations": [], "validation": {"passed": False}}
    with tempfile.TemporaryDirectory(prefix="indexed-reference-prototype-") as temporary:
        metadata = asyncio.run(proposed_metadata(str(Path(temporary) / "schema.db")))
        if sha(metadata["baseline_schema"].encode()) != reference["workers"][0]["mcp_tool_schema_sha256"]:
            raise ValueError("Baseline tool schema differs from the actual prior SDK schema")
        report["metadata_projection"] = metadata
        fixed = {}
        for name in ENCODINGS:
            costs = {key: count(name, metadata[key]) for key in (
                "baseline_schema", "proposed_schema", "baseline_instructions", "proposed_instructions")}
            costs["schema_delta"] = costs["proposed_schema"] - costs["baseline_schema"]
            costs["instructions_delta"] = costs["proposed_instructions"] - costs["baseline_instructions"]
            costs["fixed_added_tokens"] = costs["schema_delta"] + costs["instructions_delta"]
            fixed[name] = costs
            if costs["baseline_instructions"] != reference["workers"][0]["mcp_initialization_tokens"][name]["instructions"]:
                raise ValueError("Baseline instructions differ from the prior SDK initialization")
        report["metadata_costs"] = fixed
        for corpus in plan["cohorts"]:
            name = corpus["name"]
            data = load_dataset("synthetic" if name == "synthetic61" else "locomo", 61,
                                "development" if name == "synthetic61" else "heldout", 8,
                                str(args.locomo_path), 0)
            if data.fingerprint != corpus["sha256"] or len(data.queries) != corpus["queries"]:
                raise ValueError("Old cohort identity changed")
            with MemoryBook(Path(temporary) / (name + ".db"), cache_size=0) as book:
                for session in data.sessions:
                    book.ingest(session)
                for budget in BUDGETS:
                    configurations = {detail: [] for detail in (False, True)}
                    for case in data.queries:
                        native = book.recall(case.query, project=case.project, budget_chars=budget,
                                             limit=5, use_cache=False)
                        for details in (False, True):
                            payload = recall_payload(native, details=details)
                            before = _json(payload)
                            indexed = encode(payload)
                            after = _json(indexed)
                            restored = decode(indexed)
                            if restored != payload or _json(payload) != before:
                                raise ValueError("Lossy or mutating source-reference projection")
                            before_envelope, after_envelope = envelope(before), envelope(after)
                            if not details:
                                previous = expected[(name, budget, case.id)]
                                if sha(before.encode()) != previous["payload_sha256"] or sha(before_envelope.encode()) != previous["envelope_sha256"]:
                                    raise ValueError("Projection differs from the actual previous SDK response")
                            arguments = {"query": case.query, "project": case.project, "budget_chars": budget, "limit": 5}
                            if details:
                                arguments["details"] = True
                            proposed_arguments = {**arguments, "source_format": "indexed"}
                            row = {"id": case.id, "results": len(payload["results"]),
                                   "source_refs": sum(len(x["source_refs"]) for x in payload["results"]),
                                   "source_sessions": len(indexed["source_sessions"]), "reversible": True,
                                   "baseline_payload_sha256": sha(before.encode()), "indexed_payload_sha256": sha(after.encode()),
                                   "baseline_value_sha256": sha(canonical(payload).encode()),
                                   "restored_value_sha256": sha(canonical(restored).encode()), "costs": {}}
                            for encoding in ENCODINGS:
                                c = {"baseline_text": count(encoding, before), "indexed_text": count(encoding, after),
                                     "baseline_envelope": count(encoding, before_envelope), "indexed_envelope": count(encoding, after_envelope),
                                     "baseline_arguments": count(encoding, _json(arguments)),
                                     "indexed_arguments": count(encoding, _json(proposed_arguments)),
                                     "context_tokens": count(encoding, payload["context"])}
                                c["arguments_delta"] = c["indexed_arguments"] - c["baseline_arguments"]
                                for surface in ("text", "envelope"):
                                    gross = c["baseline_" + surface] - c["indexed_" + surface]
                                    c["response_savings_" + surface] = gross
                                    c["later_call_net_" + surface] = gross - c["arguments_delta"]
                                    c["first_call_net_" + surface] = gross - c["arguments_delta"] - fixed[encoding]["fixed_added_tokens"]
                                    c["first_call_baseline_total_" + surface] = c["baseline_" + surface] + c["baseline_arguments"] + fixed[encoding]["baseline_schema"] + fixed[encoding]["baseline_instructions"]
                                    c["first_call_indexed_total_" + surface] = c["first_call_baseline_total_" + surface] - c["first_call_net_" + surface]
                                row["costs"][encoding] = c
                            configurations[details].append(row)
                    for details, rows in configurations.items():
                        report["configurations"].append({"cohort": name, "budget_chars": budget,
                            "details": details, "dataset": data.description(), "metrics": summarize(rows), "rows": rows})
                    print(json.dumps({"cohort": name, "budget_chars": budget, "queries": len(data.queries), "details_modes": 2}), flush=True)
    report["source_unchanged"] = source_hash == engine_source_hash(ROOT / "src/memory_book")
    report["validation"] = {"passed": report["source_unchanged"], "configurations": len(report["configurations"]),
        "payload_projections": sum(len(c["rows"]) for c in report["configurations"]),
        "decoded_refs": sum(c["metrics"]["source_refs"] for c in report["configurations"]),
        "actual_prior_sdk_compact_responses_matched": len(expected), "runtime_modified": False}
    if (report["validation"]["configurations"] != 12 or report["validation"]["payload_projections"] != 7098
            or len(expected) != 3549 or report["prototype_sha256"] != sha(Path(__file__).read_bytes())
            or report["plan_sha256"] != sha(PLAN.read_bytes())):
        raise ValueError("Prototype matrix or evaluator changed")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    raw = (json.dumps(report, ensure_ascii=False, indent=2) + "\n").encode()
    args.output.write_bytes(gzip.compress(raw, mtime=0))
    summary = {**report, "configurations": [{k: v for k, v in c.items() if k != "rows"} for c in report["configurations"]],
               "full_report_sha256": sha(raw), "compressed_report_sha256": sha(args.output.read_bytes())}
    args.output.with_name(args.output.name.removesuffix(".json.gz") + ".summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({"validation": report["validation"], "metadata_costs": fixed}))


if __name__ == "__main__":
    main()
