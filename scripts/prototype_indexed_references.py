"""Measure a reversible opt-in reference encoding without modifying the API.

The native recall path, official compact/details projection and SDK response
models are used unchanged. Proposed schema costs are generated by FastMCP from
a placeholder signature; it does not execute a retrieval or register a live API.
"""
