"""Load independently authored cross-domain diagnostics, without indexing labels.

This is a small synthetic stress set, not a claim of real-world generalization.
Its wording is hand-authored rather than generated by the software-project
templates in long_data.py. The manifest freezes bytes before candidate scoring.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from benchmarks.data import Dataset, Evidence, QueryCase


DATA = Path(__file__).with_name("transfer_cases.json")
MANIFEST = Path(__file__).with_name("transfer_manifest.json")


class TransferDataset(Dataset):
    def description(self) -> dict:
        description = super().description()
        description.update(version="authored-transfer-1",
                           provenance=json.loads(MANIFEST.read_text(encoding="utf-8")))
        return description


def load_transfer(path: Path = DATA, *, verify: bool = True) -> Dataset:
    raw = path.read_bytes()
    if verify:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
        if hashlib.sha256(raw).hexdigest() != manifest["sha256"]:
            raise ValueError("Cross-domain diagnostic data differs from the frozen manifest")
    payload = json.loads(raw)
    dataset = TransferDataset(seed=0, split="heldout", variant="authored_transfer_v1")
    sessions = {}
    for domain in payload["domains"]:
        project = domain["project"]
        for record in domain["sessions"]:
            sid = record["id"]
            key = (project, sid)
            if key in sessions:
                raise ValueError("Duplicate source session")
            messages = [{"role": "user", "content": record["question"]},
                        {"role": "assistant", "content": record["answer"]}]
            session = {"project": project, "session_id": sid,
                       "title": record["title"], "task_id": record.get("task", sid),
                       "task_title": record.get("task", sid),
                       "created_at": record["date"] + "T09:00:00Z", "messages": messages}
            sessions[key] = session
            dataset.sessions.append(session)
        for record in domain["queries"]:
            # The complete assistant turn is the evidence target. Neither
            # queries nor these references are supplied to MemoryBook.ingest.
            def evidence(ids):
                return tuple(Evidence(sid, 0, sessions[(project, sid)]["messages"][1]["content"])
                             for sid in ids)
            dataset.queries.append(QueryCase(record["id"], record["query"], record["category"],
                                             project, evidence(record.get("required", [])),
                                             evidence(record.get("stale", [])),
                                             record.get("answerable", True)))
    ids = [case.id for case in dataset.queries]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate query ID")
    if any(case.answerable != bool(case.required) for case in dataset.queries):
        raise ValueError("Answerability and evidence labels disagree")
    return dataset
